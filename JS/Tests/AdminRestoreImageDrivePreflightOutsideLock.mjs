import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const source=readFileSync(new URL("../Services/admin.js",import.meta.url),"utf8");
const start=source.indexOf("function handleRestoreReplacedImageFromTrash(");
const end=source.indexOf("\nfunction ",start+10);
assert.ok(start>=0&&end>start,"No se encontró handleRestoreReplacedImageFromTrash");
const handler=source.slice(start,end);
const helperStart=source.indexOf("function runAdminDriveWorkOutsideScriptLock_");
const helperEnd=source.indexOf("\nfunction ",helperStart+10);
const helper=source.slice(helperStart,helperEnd);
const outside=handler.indexOf("runAdminDriveWorkOutsideScriptLock_(");
const drive=handler.indexOf("DriveApp.getFileById(driveId)");
const restore=handler.indexOf("file.setTrashed(false)");
const release=handler.indexOf("lock.releaseLock()");
const activity=handler.indexOf("recordImageAdministrationActivity(postCommitActivity.developerContext");
assert.ok(outside>0&&drive>outside&&restore>drive,"Drive preflight debe preceder a la restauración efectiva");
assert.ok(restore<release&&activity>release,"La restauración/rollback sigue bajo lock y la actividad queda post-lock");
assert.match(handler,/latestStatus!==status/);
assert.match(handler,/latestPrevious!==previous/);
assert.match(handler,/getReplacedImageRecordIdentity_\(latestRow,latestHeaders,true\)!==driveId/);
assert.match(handler,/return \{record:latest,file:driveResult\.file,alreadyRestored:driveResult\.alreadyRestored/);
assert.match(handler,/if\(verified\.alreadyRestored\)return \{status:"success",message:"La imagen ya estaba restaurada desde papelera\."/);
assert.match(handler,/setReplacedImageHistoryStatusVerified_\(sheet,rowIndex,"en_papelera"\)/);
assert.ok(helper.includes("lock.tryLock(0)"));

let locked=true,driveRan=false,revalidated=false;
const lock={hasLock:()=>locked,releaseLock(){locked=false;},tryLock(timeout){assert.equal(timeout,0);locked=true;return true;}};
const runHelper=new Function(helper+"\nreturn runAdminDriveWorkOutsideScriptLock_;")();
const result=runHelper(lock,"ADMIN_RESTORE_TRASH_IMG-1",()=>{assert.equal(locked,false);driveRan=true;return {alreadyRestored:false};},driveResult=>{assert.equal(locked,true);revalidated=true;return {alreadyRestored:driveResult.alreadyRestored};});
assert.equal(driveRan,true);assert.equal(revalidated,true);assert.equal(result.alreadyRestored,false);assert.equal(locked,true);
