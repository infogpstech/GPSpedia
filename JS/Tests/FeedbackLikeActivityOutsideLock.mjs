import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const source=readFileSync(new URL("../Services/feedback.js",import.meta.url),"utf8");
const start=source.indexOf("function handleRecordLike(payload) {");
const end=source.indexOf("\nfunction ",start+10);
assert.ok(start>=0&&end>start,"No se encontró handleRecordLike");
const handler=source.slice(start,end);
assert.match(handler,/const outcome = withFeedbackLikeLock_\(\(\) =>/);
assert.equal((handler.match(/logLikeActivityAfterAppend_\(/g)||[]).length,1,"La actividad se registra una sola vez para el útil nuevo o recuperado.");
assert.ok(handler.indexOf("const outcome = withFeedbackLikeLock_") < handler.indexOf("if (outcome.created)"),
    "La telemetría debe ejecutarse después de cerrar la sección crítica.");
assert.match(handler,/if \(outcome\.created\)[\s\S]*?logLikeActivityAfterAppend_/);
const lockStart=source.indexOf("function withFeedbackLikeLock_");
const lockEnd=source.indexOf("\nfunction ",lockStart+10);
const lock=source.slice(lockStart,lockEnd);
assert.match(lock,/lock\.waitLock\(10000\)/);
assert.match(lock,/finally\s*\{\s*lock\.releaseLock\(\)/);
const activityStart=source.indexOf("function logLikeActivityAfterAppend_");
const activityEnd=source.indexOf("\nfunction ",activityStart+10);
const activity=source.slice(activityStart,activityEnd);
assert.match(activity,/logUserActivity\(/);
assert.doesNotMatch(activity,/LockService|getScriptLock/);
console.log("FeedbackLikeActivityOutsideLock: 7/7 PASS");
