import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const ui = readFileSync("JS/Frontend/ui.js", "utf8");
const css = readFileSync("style.css", "utf8");
const start = ui.indexOf("export function mostrarDetalleTutorialModal(");
const end = ui.indexOf("\nfunction mostrarDetalleRelayModal(", start);
assert.ok(start >= 0 && end > start, "No se encontró el renderizador del modal de tutoriales.");
const render = ui.slice(start, end);
assert.match(render, /getValidatedYouTubeVideoEmbedUrl\(tutorialVideoValue\)/);
assert.match(render, /videoContainer\.className = "tutorial-video-container"/);
assert.match(render, /iframe\.src = videoEmbedUrl/);
assert.match(render, /iframe\.width = "100%"/);
assert.match(render, /iframe\.height = "315"/);
assert.doesNotMatch(render, /iframe\.loading\s*=\s*"lazy"/);
assert.match(render, /iframe\.allowFullscreen = true/);
assert.match(render, /modalDetalle\.dataset\.modalType = "tutorial"/);
assert.match(css, /#modalDetalle\[data-modal-type="tutorial"\] #detalleCompleto \.tutorial-video-container\s*\{[^}]*height:\s*315px;[^}]*min-height:\s*315px;/s);
assert.match(css, /\.tutorial-video-container\s*>\s*\.tutorial-youtube-embed\s*\{[^}]*width:\s*100%;[^}]*height:\s*315px;/s);
console.log("TutorialVideoModalLayout: 9/9 PASS");
